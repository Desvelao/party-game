/**
 * Generates bot/server/config.example.yaml from the settings schema (like `npm run config:example` for the game server).
 *   npm run bot:config:example
 */
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { MAPS, SETTINGS, key, type SettingDef } from './settings';

const show = (d: SettingDef): string => (typeof d.default === 'string' ? JSON.stringify(d.default) : String(d.default));
const allowed = (d: SettingDef): string => {
  if (d.type === 'bool') return 'true | false';
  if (d.type === 'enum') return (d.values ?? []).join(' | ');
  if (d.type === 'int') return `${d.min}-${d.max}`;
  return d.maxLength ? `text, up to ${d.maxLength} characters` : 'text';
};

export function renderExample(): string {
  const lines = [
    '# Companion server for the AI bots (npm run bot:server -- -c bot/server/config.example.yaml).',
    '# Generated by `npm run bot:config:example`; do not edit by hand.',
    '# Precedence: this file > environment variables > defaults. Extra command-line flags beat all of them.',
    '# Settings marked [live] can also be changed while running in the dashboard (Config tab, ADMIN_TOKEN);',
    '# those changes are kept in dataDir/runtime-config.json and win over this file until reset.',
    '',
  ];
  const namespaces = [...new Set(SETTINGS.map((d) => d.path[0]))];
  for (const ns of namespaces) {
    lines.push(`${ns}:`);
    for (const d of SETTINGS.filter((x) => x.path[0] === ns)) {
      const env = d.env.join(' / ');
      lines.push(`  ${`${d.path.slice(1).join('.')}: ${show(d)}`.padEnd(40)} # ${env}${d.live ? ' [live]' : ''}: ${d.help}; ${allowed(d)}`);
    }
    for (const m of MAPS.filter((x) => x.path[0] === ns)) {
      lines.push(`  # ${m.path.slice(1).join('.')}:  # [live] ${m.help}`, `  #   ${m.example}`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

export const EXAMPLE_PATH = new URL('./config.example.yaml', import.meta.url);

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(EXAMPLE_PATH, renderExample());
  console.log(`written ${EXAMPLE_PATH.pathname} (${SETTINGS.length} settings, ${MAPS.length} maps; keys: ${SETTINGS.map((d) => key(d.path)).length})`);
}
